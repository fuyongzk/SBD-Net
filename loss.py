class ClassBalancedLoss(nn.Module):
    """
    长尾动态加权 + 温和难度因子
    1. 权重上限 2.5 倍，防止某一类 dominate
    2. 默认关闭 bfnl，可手动开
    3. 权重总和归一化到 C，loss 尺度与原始 BCE 一致
    --------------------------------------------------------
    改动：beta / gamma / bfnl_weight 改为**动态可学习标量**，
         其余逻辑、设备流与旧代码完全一致，不会引入 CPU/CUDA 混用。
    """

    # 【改动2】__init__ 新增 num_classes 和 class_instance_counts 参数
    def __init__(self, num_classes=10, class_instance_counts=None, gamma=0.35, bfnl_weight=0.5):
        super().__init__()

        # 【改动3】保存类别数，并动态注册 SAMPLES_PER_CLASS 为 buffer
        self.num_classes = num_classes
        # if class_instance_counts is None:
        #     class_instance_counts = [100] * num_classes  # 兜底，不建议使用
        # assert len(class_instance_counts) == num_classes, \
        #     f"实例数长度{len(class_instance_counts)}与类别数{num_classes}不匹配"
        self.register_buffer(
            'SAMPLES_PER_CLASS',
            torch.tensor(class_instance_counts, dtype=torch.float32)
        )

        # ----------  唯一修改  ----------
        # 把 3 个静态超参变成可学习标量，初值用原默认值
        # 用 PyTorch 实现 logit，避免 numpy 版本问题；tensor 先放 CPU，后续跟随 model.cuda()
        def _logit(p):
            p = torch.as_tensor(p).clamp(1e-7, 1 - 1e-7)
            return (p / (1 - p)).log()

        self._gamma_raw = nn.Parameter(_logit((gamma - 0.1) / 0.4))  # 映射到 0.1~0.5
        self._bfnl_raw = nn.Parameter(_logit(bfnl_weight / 5.))  # 映射到 0~5
        # ---------------------------------
        # 下面全部保持与原代码完全一致
        self.register_buffer('base_weights', None)
        self.register_buffer('class_weights', None)

        # 【改动4】_ap_ema 从 torch.zeros(5) 改为 torch.zeros(num_classes)，适配8类
        self.register_buffer('_ap_ema', torch.zeros(num_classes))

        self.register_buffer('_last_epoch', torch.tensor(-1))
        self._init_weights()  # 把 base_weights 放到 buffer

        # ===== 新增可学习阈值 =====
        # 初始值 0.3/0.5 映射到 logit 空间
        self._thresh_fp_raw = nn.Parameter(torch.logit(torch.tensor(0.4)))
        self._thresh_fn_raw = nn.Parameter(torch.logit(torch.tensor(0.5)))

    @property
    def thresh_fp(self):
        return torch.sigmoid(self._thresh_fp_raw)  # 保持 Tensor

    @property
    def thresh_fn(self):
        return torch.sigmoid(self._thresh_fn_raw)

    # ------------------------------------------------------------------
    def _init_weights(self):
        # 【改动5】引用方式不变（self.SAMPLES_PER_CLASS 现在已是动态注册的 buffer）
        base = 1.0 / (self.SAMPLES_PER_CLASS + 1e-5)
        base = base / base.max() * 2.0
        self.register_buffer('base_weights', base.clone())
        self.register_buffer('class_weights', base.clone())

    @property
    def gamma(self):
        return torch.sigmoid(self._gamma_raw) * 0.4 + 0.1

    @property
    def bfnl_weight(self):
        return torch.sigmoid(self._bfnl_raw) * 5.0

    # ------------------------------------------------------------------
    # @torch.no_grad()
    # def update_weights(self, ap50: np.ndarray, epoch: int,
    #                    mutual_fp: float = 0.0, mutual_fn: float = 0.0,

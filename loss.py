    #     #             return
    #
    #     # 1. 如果不是 10 的倍数，并且已经更新过，直接返回
    #     if (epoch % 10 != 0) and (epoch == self._last_epoch.item()):
    #         return
    #
    #     self._last_epoch.copy_(torch.tensor(epoch))
